from playwright.sync_api import sync_playwright
from pathlib import Path
import re
folder=Path('/mnt/data/adc-ascent-app')
html=(folder/'index.html').read_text()
html=re.sub(r'<script[^>]+src="[^"]+"[^>]*></script>','',html)
html=re.sub(r'<link[^>]+href="[^"]+"[^>]*>','',html)
css=(folder/'styles.css').read_text().split('\n',1)[1]
data=(folder/'data.js').read_text()
app=(folder/'app.js').read_text()
errors=[]
def load(page):
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.goto('about:blank')
 page.evaluate('''() => { const memory = {}; Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:(k)=>memory[k]||null,setItem:(k,v)=>memory[k]=v,removeItem:(k)=>delete memory[k]}}); }''')
 page.set_content(html)
 page.evaluate("(css) => { const style=document.createElement('style');style.textContent=css;document.head.appendChild(style); }",css)
 page.evaluate("(code) => { eval(code); }",data)
 page.evaluate("(code) => { eval(code); }",app)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':950},device_scale_factor=1)
 load(page)
 print('TITLE',page.title());print('H1',page.locator('h1').all_text_contents());print('nav count',page.locator('[data-nav]').count());print('js errors:', errors)
 page.screenshot(path=str(folder/'preview-desktop.png'),full_page=True)
 assert 'Your road to Master' in page.locator('body').inner_text()
 page.get_by_role('button',name='Skill Tree',exact=True).click()
 assert 'ADC mastery tree' in page.locator('body').inner_text()
 print('Metrics',page.locator('[data-metric]').count())
 page.get_by_role('button',name='Add assessment').first.click()
 page.locator('#assessment-form [name=note]').fill('Controlled drill 6 opportunities in practice tool.')
 page.locator('#assessment-form button[type=submit]').click()
 assert page.locator('body').get_by_text('RECORDED PASS').count()>0
 page.get_by_role('button',name='Champion Forge').click()
 print('Champion contracts',page.locator('[data-contract]').count())
 page.get_by_role('button',name='Training Plan').click()
 page.get_by_role('button',name='Create today’s mission').click()
 assert page.locator('[data-quest]').count()==4
 page.locator('[data-quest]').first.check()
 page.get_by_role('button',name='Match History').click()
 page.get_by_role('button',name='Add match').click()
 page.locator('#match-form button[type=submit]').click()
 assert 'VICTORY' in page.locator('body').inner_text()
 page.get_by_role('button',name='VOD Review Lab').click()
 page.locator('#review-time').fill('11:32')
 page.locator('#review-decision').fill('Enemy jungler missing and I stepped too far for a contested wave. Next time I will prioritize safety.')
 page.locator('#review-form button[type=submit]').click()
 assert '11:32' in page.locator('body').inner_text()
 page.get_by_role('button',name='Performance Insights').click()
 assert 'Performance Insights' in page.locator('body').inner_text()
 page.get_by_role('button',name='Settings & Data').click()
 assert 'Settings' in page.locator('body').inner_text()
 page.screenshot(path=str(folder/'preview-settings.png'),full_page=True)
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 load(mobile)
 mobile.screenshot(path=str(folder/'preview-mobile.png'),full_page=True)
 print('mobile scrollwidth',mobile.evaluate('document.documentElement.scrollWidth'),'viewport',mobile.evaluate('window.innerWidth'))
 mobile.get_by_role('button',name='Open navigation').click()
 mobile.get_by_role('button',name='Skill Tree').click()
 print('mobile H1',mobile.locator('h1').inner_text())
 browser.close()
print('errors',errors)
assert not errors,errors
